/**
 * AISC Steel Section Database
 * Source: AISC Steel Construction Manual, 16th Ed.
 * Contains W-shapes, HSS rectangular, and Pipe sections.
 *
 * See NOTICE for the standards attribution and disclaimer.
 */

export interface AISCSection {
  name: string;
  type: 'W' | 'HSS' | 'Pipe';
  d: number;    // Depth (in)
  bf: number;   // Flange width (in)
  tf: number;   // Flange thickness (in)
  tw: number;   // Web thickness (in)
  A: number;    // Area (in²)
  Ix: number;   // Strong axis I (in⁴)
  Iy: number;   // Weak axis I (in⁴)
  Sx: number;   // Strong axis S (in³)
  Sy: number;   // Weak axis S (in³)
  Zx: number;   // Strong axis Z (in³)
  Zy: number;   // Weak axis Z (in³)
  rx: number;   // Strong axis r (in)
  ry: number;   // Weak axis r (in)
  J: number;    // Torsional constant (in⁴)
  weight: number; // Weight (lb/ft)
}

// W-shapes: name, type, d, bf, tf, tw, A, Ix, Iy, Sx, Sy, Zx, Zy, rx, ry, J, weight
function w(name: string, d: number, bf: number, tf: number, tw: number, A: number, Ix: number, Iy: number, Sx: number, Sy: number, Zx: number, Zy: number, rx: number, ry: number, J: number, weight: number): AISCSection {
  return { name, type: 'W', d, bf, tf, tw, A, Ix, Iy, Sx, Sy, Zx, Zy, rx, ry, J, weight };
}

function hss(name: string, d: number, bf: number, tw: number, A: number, Ix: number, Iy: number, Sx: number, Sy: number, Zx: number, Zy: number, rx: number, ry: number, J: number, weight: number): AISCSection {
  return { name, type: 'HSS', d, bf, tf: tw, tw, A, Ix, Iy, Sx, Sy, Zx, Zy, rx, ry, J, weight };
}

