/**
 * Search sections by name prefix (case-insensitive).
 */
export function searchSections(query: string): AISCSection[] {
  const q = query.toUpperCase().trim();
  if (!q) return AISC_SECTIONS;
  return AISC_SECTIONS.filter((s) => s.name.toUpperCase().includes(q));
}

/**
 * Filter sections by type.
 */
export function filterSectionsByType(type: AISCSection['type']): AISCSection[] {
  return AISC_SECTIONS.filter((s) => s.type === type);
}

/**
 * Convert an AISCSection to the app's Section type format.
 */
export function aiscToSection(aisc: AISCSection): {
  id: string;
  name: string;
  A: number;
  Ix: number;
  Iy: number;
  J: number;
  Sx: number;
  Sy: number;
  Zx: number;
  Zy: number;
  rx: number;
  ry: number;
  d: number;
  bf: number;
  tf: number;
  tw: number;
} {
  return {
    id: aisc.name,
    name: aisc.name,
    A: aisc.A,
    Ix: aisc.Ix,
    Iy: aisc.Iy,
    J: aisc.J,
    Sx: aisc.Sx,
    Sy: aisc.Sy,
    Zx: aisc.Zx,
    Zy: aisc.Zy,
    rx: aisc.rx,
    ry: aisc.ry,
    d: aisc.d,
    bf: aisc.bf,
    tf: aisc.tf,
    tw: aisc.tw,
  };
}
